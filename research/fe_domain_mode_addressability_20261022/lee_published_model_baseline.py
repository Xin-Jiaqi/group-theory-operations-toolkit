#!/usr/bin/env python3
"""Baseline test of Zhou et al., PRL 137, 076401 (2026), Eq. (3).

H = k^2/(2m) + t*tau_x + Delta*tau_z
    + alpha*tau_z*(sigma_x*k_y - sigma_y*k_x).

Dimensionless sanity parameters, NOT a material fit. The Boltzmann response
uses the band-diagonal structure of Eq. (2); an isotropic angular factor is
removed because it cancels in the normalized ratio.

Tests:
* layer-odd in-plane spin response is even in Delta;
* global in-plane spin response is odd in Delta and vanishes at Delta=0;
* layer-odd out-of-plane spin response is exactly zero in this Hamiltonian.
The last is an analytical no-go: each band can be chosen as a layer state
times an in-plane spin-helicity state, so <tau_z sigma_z>=0. Scalar changes
t_perp(u) or Delta(u) cannot create the proposed slide-linear Sz response.

This is a reproduction sanity check, NOT a novelty or material claim.
Run: python lee_published_model_baseline.py [--nk 16000] [--points 161].
"""
import argparse
import csv
import json
import numpy as np


def response(delta, t=1.0, alpha=0.5, mass=1.0, mu=0.0,
             temperature=0.02, kmax=4.5, nk=16000):
    if temperature <= 0 or nk < 100 or kmax <= 0:
        raise ValueError("temperature>0, nk>=100 and kmax>0 are required")
    k = np.linspace(1e-6, kmax, nk)
    dk = k[1] - k[0]
    num_layer_odd_sy = num_global_sy = denominator = 0.0
    for helicity in (-1, 1):
        e_soc = np.sqrt(t*t + (delta + helicity*alpha*k)**2)
        for branch in (-1, 1):
            energy = k*k/(2*mass) + branch*e_soc
            x = np.clip((energy-mu)/(2*temperature), -350, 350)
            minus_dfde = 1/(4*temperature)/np.cosh(x)**2
            radial_velocity = (k/mass + branch*(delta + helicity*alpha*k)
                               *helicity*alpha/e_soc)
            # <sigma_y>=-helicity*cos(theta);
            # <tau_z>=branch*(Delta+helicity*alpha*k)/e_soc.
            # Common angular integral of cos(theta)^2 cancels in the ratio.
            layer_odd_sy = (-helicity*branch*(delta+helicity*alpha*k)/e_soc)
            global_sy = -helicity
            weight = k*dk*minus_dfde
            num_layer_odd_sy += np.sum(weight*layer_odd_sy*radial_velocity)
            num_global_sy += np.sum(weight*global_sy*radial_velocity)
            denominator += np.sum(weight*radial_velocity**2)
    return {
        "chi_layer_odd_Sy_jx": float(num_layer_odd_sy/denominator),
        "chi_global_Sy_jx": float(num_global_sy/denominator),
        # Exact analytic result for the DC intraband/Boltzmann response of Eq. (3).
        "chi_layer_odd_Sz_jy": 0.0,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--nk", type=int, default=16000)
    parser.add_argument("--points", type=int, default=161)
    parser.add_argument("--output", default="lee_baseline.csv")
    args = parser.parse_args()
    deltas = np.linspace(-0.8, 0.8, args.points)
    rows = [{"Delta_over_t": float(d), **response(float(d), nk=args.nk)}
            for d in deltas]
    reverse = list(reversed(rows))
    even_error = max(abs(a["chi_layer_odd_Sy_jx"]-b["chi_layer_odd_Sy_jx"])
                     for a, b in zip(rows, reverse))
    odd_error = max(abs(a["chi_global_Sy_jx"]+b["chi_global_Sy_jx"])
                    for a, b in zip(rows, reverse))
    z_error = max(abs(r["chi_layer_odd_Sz_jy"]) for r in rows)
    assert even_error < 1e-10, even_error
    assert odd_error < 1e-10, odd_error
    assert z_error == 0.0
    with open(args.output, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    result = {
        "model": "published LEE minimal k.p Hamiltonian, dimensionless sanity parameters",
        "parameters": {"t": 1.0, "alpha": 0.5, "mass": 1.0, "mu": 0.0,
                       "temperature": 0.02, "kmax": 4.5, "nk": args.nk},
        "parity_checks": {
            "layer_odd_Sy_even_in_Delta_max_abs_error": even_error,
            "global_Sy_odd_in_Delta_max_abs_error": odd_error,
            "layer_odd_Sz_exact_zero": z_error == 0.0},
        "delta_zero": rows[args.points//2],
        "interpretation": "No Sz response can be generated by registry-dependent scalar t_perp or Delta alone in this model. A physical spin-z SOC vertex must be derived from source-backed microscopic physics before computing the proposed slide derivative.",
        "novelty": "none claimed"}
    print(json.dumps(result, indent=2))
    print(f"Wrote {args.output}; parity tests PASS")


if __name__ == "__main__":
    main()
