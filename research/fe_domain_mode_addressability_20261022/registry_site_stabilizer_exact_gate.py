"""Exact hex registry-torus stabilizer gate for layer-odd/even axial Sz/current.

Assumptions: identical layers with an unperturbed family generated by C3z,
vertical mirror mx, and horizontal layer-exchange mz. 2D integer matrices
act on FRACTIONAL registry x,y mod 1. Response representation includes
mirror axial-spin sign, and mz layer parity. Fixed-current real DC response
under these unitary operations only; NO claim about magnetic MSG,
antiunitary finite omega, Kubo nonzero, or general mathematical novelty.

Outputs true group stabilizer dimensions at six BSF registry points.
A/B/C admit a *one-dimensional layer-even response direction* but
the layer-odd response must vanish. G/M/N forbid both channels.
Run python registry_site_stabilizer_exact_gate.py (Python standard library).
"""
from fractions import Fraction as F

I=(1,0,0,1)
NEG=(-1,0,0,-1)
C3=(0,-1,1,-1)
MX=(-1,1,0,1)

def mul(a,b):
    return (a[0]*b[0]+a[1]*b[2],
            a[0]*b[1]+a[1]*b[3],
            a[2]*b[0]+a[3]*b[2],
            a[2]*b[1]+a[3]*b[3])

def neg(a):
    return tuple(-v for v in a)

def act(a,p):
    return ((a[0]*p[0]+a[1]*p[1])%1,
            (a[2]*p[0]+a[3]*p[1])%1)

def fixed_dim(ds):
    vectors=[]
    for d in ds:
        vectors.extend(((d[0]-1,d[1]),(d[2],d[3]-1)))
    vectors=[v for v in vectors if v!=(0,0)]
    if not vectors:
        return 2
    if any(a*d-b*c for a,b in vectors for c,d in vectors):
        return 0
    return 1

def group(parity):
    generators=[(C3,C3),(MX,neg(MX)),(NEG,NEG if parity==-1 else I)]
    g={I:I}; todo=[I]
    while todo:
        a=todo.pop()
        for b,db in generators:
            c=mul(b,a)
            dc=mul(db,g[a])
            if c not in g:
                g[c]=dc
                todo.append(c)
            else:
                assert g[c]==dc,("representation mismatch",c)
    assert len(g)==12
    return g

def gate():
    points={
        "G":(F(0),F(0)),
        "A":(F(1,2),F(0)),
        "B":(F(0),F(1,2)),
        "C":(F(1,2),F(1,2)),
        "M":(F(1,3),F(2,3)),
        "N":(F(2,3),F(1,3))}
    groups={"layer_odd":group(-1),"layer_even":group(1)}
    expected_even={"G":0,"A":1,"B":1,"C":1,"M":0,"N":0}
    for name,p in points.items():
        dims={}
        for kind,g in groups.items():
            stabilizer=[d for a,d in g.items() if act(a,p)==p]
            dims[kind]=fixed_dim(stabilizer)
        assert dims["layer_odd"]==0
        assert dims["layer_even"]==expected_even[name]
        print(name,str(p),"layer-odd",dims["layer_odd"],
              "layer-even",dims["layer_even"])
    for kind,g in groups.items():
        forced=set()
        for i in range(12):
            for j in range(12):
                p=(F(i,12),F(j,12))
                ds=[d for a,d in g.items() if act(a,p)==p]
                if fixed_dim(ds)==0:forced.add(p)
        expected=set(points.values()) if kind=="layer_odd" else {
            points[x] for x in ("G","M","N")}
        assert forced==expected,(kind,forced-expected,expected-forced)
        print("PASS",kind,"forced zeros",len(forced),
              "on exhaustive 12x12 rational grid")
    print("PASS 12 group elements, exact rational site stabilizers")
    print("Only symmetry-zero/direction constraints; physical values not guaranteed")

if __name__=="__main__":
    gate()
